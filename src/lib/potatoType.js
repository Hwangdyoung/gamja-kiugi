/* 가장 많이 고른 유형. 같으면 더 나중 문항에서 고른 유형 (팀원 시안과 같은 규칙) */
export function potatoOf(answers) {
  const score = Object.fromEntries(POTATO_ORDER.map((k) => [k, 0]));
  const last = Object.fromEntries(POTATO_ORDER.map((k) => [k, -1]));
  answers.forEach((t, i) => {
    if (t && t in score) {
      score[t] += 1;
      last[t] = i;
    }
  });
  let best = POTATO_ORDER[0];
  for (const t of POTATO_ORDER) {
    if (score[t] > score[best] || (score[t] === score[best] && last[t] > last[best])) best = t;
  }
  return best;
}

